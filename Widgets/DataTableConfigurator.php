            'action' => $this->buildUxonForActionEditSetup()
        ]));
    }

    public function createButtonToDeleteSetup(iHaveButtons $table) : Button
    {
        return $table->createButton(new UxonObject([
            'hide_caption' => true,
            'caption' => $this->translate('ACTION.DELETEOBJECT.NAME'),
            'icon' => 'trash-o',
            'disabled_if' => [
                'operator' => 'AND',
                'conditions' => [
                    [
                        "value_left" => "=~input!CREATED_BY_USER",
                        "comparator" => "!==",
