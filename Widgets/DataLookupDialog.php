<?php
namespace exface\Core\Widgets;

use exface\Core\Exceptions\Widgets\WidgetConfigurationError;
use exface\Core\Factories\WidgetFactory;
use exface\Core\Interfaces\WidgetInterface;
use exface\Core\Interfaces\Widgets\iShowData;
use exface\Core\Interfaces\Widgets\iTriggerAction;
use exface\Core\Interfaces\Widgets\iUseInputWidget;
use exface\Core\Interfaces\Widgets\iSupportMultiSelect;
use exface\Core\Interfaces\Model\MetaAttributeInterface;
use exface\Core\DataTypes\BooleanDataType;

/**
 * An advanced search dialog allowing the user to search and select data entries.
 * 
 * Buttons in the DataLookupDialog receive the selected entries as input data. For example, you can use a `SendToWidget`
 * action to send selected entries to another widget - this approach is used by `InputComboTable` to generate their
 * built-in lookup dialogs.
 * 
 * If no widget is specified by the user, the action will produce an autogenerated
 * `DataLookupDialog` - a search dialog based on default-display settings in the metamodel 
 * of the object being searched. This basically means, that the lookup-dialog will show the 
 * same table as the `InputComboTable` and provide filter over every visible column.
 * 
 * You can customize the lookup dialog by specifying a custom widget to be shown:
 * 
 * ```
 * {
 *  "widget_type": "DataLookupDialog",
 *  "widgets": [
 *      {
 *          "object_alias": "...",
 *          "widget_type": "DataTable",
 *          "filters": [
 *              {
 *                "attribute_alias": "..."
 *              }
 *          ],
 *          "columns": [
 *              {
 *                "attribute_alias": "..."
 *              }
 *          ]
 *      }
 *  ]
 * }
 * 
 * ```
 *
 * @author Andrej Kabachnik
 *        
 */
class DataLookupDialog extends Dialog
{
    private ?bool $multiSelect = null;
    private ?string $uidAttributeAlias = null;
    private ?string $labelAttributeAlias = null;
    
    private $dataWidget = nulL;
    private ?DataColumn $uidColumn = null;
    private ?DataColumn $labelColumn = null;
    
    /**
     * 
     * {@inheritDoc}
     * @see \exface\Core\Widgets\Container::getWidgets()
     */
    public function getWidgets(callable $filter = null)
    {
        if ($this->isDataWidgetInitialized() === false) {
            $data_table = $this->createLookupTable();
            $this->dataWidget = $data_table;
            $this->addWidget($data_table);
        }
        
        return parent::getWidgets($filter);
    }
    
    protected function isDataWidgetInitialized() : bool
    {
        return $this->dataWidget !== null || parent::hasWidgets() === true;
    }

    /**
     * Creates the default lookup table.
     * 
     * NOTE: this is the base table, which does not include the information from the context in which the
     * lookup was called: e.g. this table does not know if it was called by an InputComboTable or by a
     * user-defined button. This information is added by the specific action - e.g. `ShowLookupDialog`.
     * 
     * @return iShowData
     */
    protected function createLookupTable() : iShowData
    {
        $lookupObj = $this->getMetaObject();
        /* @var $data_table \exface\Core\Widgets\Data */
        $data_table = WidgetFactory::create($this->getPage(), 'DataTableResponsive', $this);
        $data_table->setMetaObject($lookupObj);
        $data_table->setMultiSelect($this->getMultiSelect());
        $data_table->setMultiSelectSavedOnNavigation(true);
        $data_table->getPaginator()->setCountAllRows(false);
        // Disabled setups for the lookup table to prevent recursively nested dialogs: the setups table has
        // buttons, that include other tables, which in-turn might have setups. On the other hand, it is
        // extremely unlikely, that people would save setups for lookup tables: after all, this would mean,
        // that certain lookup dialogs are used really often, which is probably not a very good idea. 
        $data_table->setConfiguratorSetupsEnabled(false);

        // If the table has no columns, determine them from the model
        if ($data_table->hasColumns() === false) {
            $defaultDisplayAttrs = $lookupObj->getAttributes()->getDefaultDisplayList();
            switch (true) {
                // If the object has default display attributes, use them
                case $defaultDisplayAttrs->isEmpty() === false:
                    foreach ($defaultDisplayAttrs as $attr) {
                        $data_table->addColumn($data_table->createColumnFromAttribute($attr), $attr->getDefaultDisplayOrder());
                    }
                    break;
                // Otherwise use the object's label if there is one
                case $lookupObj->hasLabelAttribute() === true:
                    $data_table->addColumn($data_table->createColumnFromAttribute($lookupObj->getLabelAttribute()));
                    break;
                // If neither a label nor default-display attributes exist, see if the UID is not hidden
                case $defaultDisplayAttrs->isEmpty() && $lookupObj->hasUidAttribute() === true && $lookupObj->getUidAttribute()->isHidden() === false:
                    $data_table->addColumn($data_table->createColumnFromAttribute($lookupObj->getUidAttribute()));
                    break;
                // Since we need columns a any case, just take the first 4 attributes if nothing else
                // helps
                default:
                    $cnt = 0;
                    foreach ($lookupObj->getAttributes() as $attr) {
                        if ($attr->isHidden() === false) {
                            $data_table->addColumn($data_table->createColumnFromAttribute($attr));
                            $cnt++;
                        }
                        if ($cnt >= 4) {
                            break;
                        }
                    }
            }
        }

        $dataConfigurator = $data_table->getConfiguratorWidget();
        foreach($data_table->getColumns() as $col) {
            if ($col->isHidden() === false && $col->isBoundToAttribute() === true) {
                if ($col->isBoundToLabelAttribute() === true || ($col->getAttribute()->getRelationPath()->isEmpty() === false && $col->getAttribute()->isLabelForObject() === true)) {
                    $filterAttrAlias = $col->getAttribute()->getRelationPath()->toString();
                } else {
                    $filterAttrAlias = $col->getAttributeAlias();
                }
                if ($filterAttrAlias !== '' || $filterAttrAlias !== null) {
                    $filterWidget = $dataConfigurator->createFilterForAttributeAlias($filterAttrAlias);
                    $filterInput = $filterWidget->getInputWidget();
                    // Boolean filters render as a single-select Yes/No/All (see InputCheckBox::transformIntoSelect()),
                    // so forcing multi-select here would produce a nonsensical multi-value boolean filter.
                    $isBoolean = $filterWidget->isBoundToAttribute()
                        && $filterWidget->getAttribute()->getDataType() instanceof BooleanDataType;
                    if ($filterInput instanceof iSupportMultiSelect && ! $isBoolean) {
                        $filterInput->setMultiSelect(true);
                    }
                    $dataConfigurator->addFilter($filterWidget);
                }
            }
        }

        if ($lookupObj->hasLabelAttribute() === true) {
            $labelAlias = $lookupObj->getLabelAttributeAlias();
            if (! $data_table->getColumnByAttributeAlias($labelAlias)
                && ! $data_table->getColumnByDataColumnName(MetaAttributeInterface::OBJECT_LABEL_ALIAS)
            ) {
                $this->labelColumn = $data_table->createColumnFromAttribute($lookupObj->getLabelAttribute());
                $data_table->addColumn($this->labelColumn);
            }
        }
        
        // Add UID and label attributes explicitly defined for the lookup dialog as hidden columns if the table does
        // not contain them yet. This is important as the lookup data MUST contain these attributes.
        if (null !== $attrAlias = $this->getCustomUidAttributeAlias()) {
            if (! $col = $data_table->getColumnByAttributeAlias($attrAlias)) {
                $data_table->addColumn($data_table->createColumnFromAttribute($lookupObj->getAttribute($attrAlias), null, true));
            }
            $this->uidColumn = $col;
        }
        if (null !== $attrAlias = $this->getCustomLabelAttributeAlias()) {
            if (! $col = $data_table->getColumnByAttributeAlias($attrAlias)) {
                $data_table->addColumn($data_table->createColumnFromAttribute($lookupObj->getAttribute($attrAlias), null, true));
            }
            $this->labelColumn = $col;
        }
        
        return $data_table;
    }
    
    /**
     * Set to TRUE to allow selection of multiple entries in the lookup dialog.
     * 
     * If the lookup dialog is called from an input widget (e.g. `InputComboTable`) this setting
     * is inherited from that input. Otherwise it is `false` by default.
     * 
     * @uxon-property multi_select
     * @uxon-type boolean
     * @uxon-default false
     * 
     * @param bool $trueOrFalse
     * @return DataLookupDialog
     */
    public function setMultiSelect(bool $trueOrFalse) : DataLookupDialog
    {
        $this->multiSelect = $trueOrFalse;
        $dataWidget = $this->getDataWidget();
        if ($dataWidget instanceof iSupportMultiSelect) {
            $dataWidget->setMultiSelect($trueOrFalse);
        }
        return $this;
    }
    
    /**
     * 
     * @return bool|NULL
     */
    public function getMultiSelect() : ?bool
    {
       $srcWidget = $this->getParent();
        if ($srcWidget instanceof iUseInputWidget) {
            $inputWidget = $srcWidget->getInputWidget();
            if ($inputWidget && ($inputWidget instanceof iSupportMultiSelect)){
                return $inputWidget->getMultiSelect();
            }
        }
        return null;
    }
    
    /**
     * 
     * @return Data
     */
    public function getDataWidget() : Data
    {
        return $this->dataWidget ?? $this->getWidgetFirst();
    }

    public function getTriggerWidget() : ?iTriggerAction
    {
        if ($this->hasParent() && $this->getParent() instanceof iTriggerAction) {
            return $this->getParent();
        }
        return null;
    }

    public function getTriggerInputWidget() : ?WidgetInterface
    {
        $trigger = $this->getTriggerWidget(); 
        if ($trigger !== null && ($trigger instanceof iUseInputWidget)) {
            return $trigger->getInputWidget();
        }
        return null;
    }

    /**
     * Attribute to get lookup values from (= UID column of lookup widget).
     * 
     * If not set, the regular UID column of the main lookup widget (table) will be used. This in-turn is usually
     * the UID of the widgets object.
     * 
     * @uxon-property uid_attribute_alias
     * @uxon-type metamodel:attribute
     * 
     * @param string $alias
     * @return $this
     */
    public function setUidAttributeAlias(string $alias) : DataLookupDialog
    {
        $this->uidAttributeAlias = $alias;
        if ($this->isDataWidgetInitialized() === true) {
            $dataWidget = $this->getDataWidget();
            if (! $col = $dataWidget->getColumnByAttributeAlias($alias)) {
                $col = $dataWidget->createColumnFromAttribute($dataWidget->getMetaObject()->getAttribute($alias), null, true);
                $dataWidget->addColumn($col);
            }
            $this->uidColumn = $col;
        }
        return $this;
    }

    /**
     * @return string|null
     */
    protected function getCustomUidAttributeAlias() : ?string
    {
        return $this->uidAttributeAlias;
    }

    /**
     * Attribute to use as LABEL for lookup rows.
     *
     * If not set, the label attribute of the object of the main lookup widget (table) will be used.
     *
     * @uxon-property label_attribute_alias
     * @uxon-type metamodel:attribute
     *
     * @param string $alias
     * @return $this
     */
    public function setLabelAttributeAlias(string $alias) : DataLookupDialog
    {
        $this->labelAttributeAlias = $alias;
        if ($this->isDataWidgetInitialized() === true) {
            $dataWidget = $this->getDataWidget();
            if (! $col = $dataWidget->getColumnByAttributeAlias($alias)) {
                $col = $dataWidget->createColumnFromAttribute($dataWidget->getMetaObject()->getAttribute($alias), null, true);
                $dataWidget->addColumn($col);
            }
            $this->labelColumn = $col;
        }
        return $this;
    }

    /**
     * @return string|null
     */
    protected function getCustomLabelAttributeAlias() : ?string
    {
        return $this->labelAttributeAlias;
    }

    /**
     * Returns the column of the data widget, that contains the lookup values (= row UIDs of the data widget)
     * 
     * @return DataColumn
     */
    public function getUidColumn() : DataColumn
    {
        if ($this->uidColumn === null) {
            $dataWidget = $this->getDataWidget();
            // If there is no UID column defined, see if the lookup widget has a UID column itself.
            $uidCol = $dataWidget->getUidColumn();
            // If not, see if the lookup widget has exactly one aggregation column, and use that as UID column
            // because being the only aggregation it will definitely produce unique values.
            if ($uidCol === null && count($dataWidget->getAggregations()) === 1) {
                $uniqueAlias = $dataWidget->getAggregations()[0];
                $uidCol = $dataWidget->getColumnByAttributeAlias($uniqueAlias);
            }
            // If there is still no UID column - we cant use the lookup dialog properly.
            if ($uidCol === null) {
                throw new WidgetConfigurationError($this, 'No UID column found in DataLookupDialog widget!');
            }
            return $uidCol;
        }
        return $this->uidColumn;
    }

    /**
     * Returns the column of the data widget, that can be used for labels of lookup values
     * 
     * @return DataColumn
     */
    public function getLabelColumn() : DataColumn
    {
        if ($this->labelColumn === null) {
            $dataWidget = $this->getDataWidget();
            // Try to get the column from the object label attribute
            if ($dataWidget->getMetaObject()->hasLabelAttribute() === true) {
                $labelCol = $dataWidget->getColumnByAttributeAlias($dataWidget->getMetaObject()->getLabelAttributeAlias());
            }
            // If no label attribute or no column for it, take the first unconditionally visible column
            if ($labelCol === null) {
                foreach ($dataWidget->getColumns() as $col) {
                    if ($col->isHidden() === false && $col->getHiddenIf() === null) {
                        return $col;
                    }
                }
            }
            // In contrast to the UID column, there will always be a label column unless the lookup widget does not
            // show anything at all (which will be wrong anyway).
        }
        return $this->labelColumn;
    }
}